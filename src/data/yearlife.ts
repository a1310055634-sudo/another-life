/** 生活流行前缀（年志内一眼可辨的次要条目样式） */
export const YEARLIFE_PREFIX = '——'

/** 变体槽位数（第 71 轮为 4，第 101 轮扩到 6）。抽取散列与季节取模一行未改。 */
export const YEARLIFE_VARIANTS = 6

/**
 * 取本年生活流行（纯函数，散列支流零 rng）：>75 岁返回 null（调用方守门）。
 * 同 seed 同年龄必得同行；季节由散列低位选、变体由高位选，跨局自然分散。
 * 第 101 轮：变体槽位 4→6（年志池 48→72），仅取模基数变化——
 * 散列 h 的构造、季节低位选法均未动，故季节分布与第 71 轮逐位一致。
 */
export function pickYearLifeLine(seed: number, age: number): string | null {
  if (age > 75) return null
  const seg = age <= 40 ? 0 : age <= 60 ? 1 : 2
  const h =
    ((seed >>> 0) ^ (Math.imul(age, 0x9e3779b1) >>> 0) ^ (Math.imul(age - 18, 0x85ebca6b) >>> 0)) >>> 0
  const season = h % 4
  const variant = Math.floor(h / 4) % YEARLIFE_VARIANTS
  return YEARLIFE_PREFIX + YEARLIFE[season][seg][variant]
}
